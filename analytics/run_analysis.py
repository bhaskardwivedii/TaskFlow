"""
Load the exported star schema into DuckDB (with PK/FK constraints enforced),
run every query in sql/queries.sql and write the results to REPORT.md.

    pip install duckdb
    python analytics/run_analysis.py            # uses analytics/data/*.csv
    python analytics/run_analysis.py --db taskflow.duckdb   # also persist a .duckdb file for Power BI / DBeaver
"""
import argparse
import re
from pathlib import Path

import duckdb

HERE = Path(__file__).resolve().parent
LOAD_ORDER = [  # dimensions before facts so foreign keys resolve
    "dim_date", "dim_team", "dim_user", "dim_project",
    "fact_task", "fact_task_event", "fact_status_interval", "bridge_task_label",
]


def parse_queries(sql: str):
    blocks = re.split(r"(?m)^-- name: ", sql)[1:]
    for block in blocks:
        name, _, body = block.partition("\n")
        question = re.search(r"(?m)^-- question: (.*)$", body)
        yield name.strip(), (question.group(1) if question else ""), body.strip().rstrip(";")


def to_markdown(columns, rows):
    fmt = lambda v: "" if v is None else (f"{v:,.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v))
    out = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    out += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(HERE / "data"))
    ap.add_argument("--db", default=":memory:")
    ap.add_argument("--report", default=str(HERE / "REPORT.md"))
    args = ap.parse_args()

    con = duckdb.connect(args.db)
    con.execute("SET TimeZone = 'Asia/Kolkata'")
    for t in reversed(LOAD_ORDER):
        con.execute(f"DROP TABLE IF EXISTS {t}")
    con.execute((HERE / "sql" / "00_schema.sql").read_text())
    for t in LOAD_ORDER:
        con.execute(f"INSERT INTO {t} SELECT * FROM read_csv_auto(?, header=true, nullstr='')", [str(Path(args.data) / f"{t}.csv")])
        print(f"loaded {t:<22} {con.execute(f'SELECT COUNT(*) FROM {t}').fetchone()[0]:>7} rows")

    report = ["# TaskFlow — SQL analysis report", "",
              "Generated by `analytics/run_analysis.py` from the star-schema export. "
              "Each section is one query in `analytics/sql/queries.sql`.", ""]
    for name, question, sql in parse_queries((HERE / "sql" / "queries.sql").read_text()):
        cur = con.execute(sql)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        print(f"\n== {name}: {question}\n{to_markdown(cols, rows)}")
        report += [f"## {name.replace('_', ' ', 1)}", f"*{question}*", "", to_markdown(cols, rows), ""]

    Path(args.report).write_text("\n".join(report))
    print(f"\nreport written to {args.report}")


if __name__ == "__main__":
    main()
